from pygost.gost3411_12 import GOST341112
from elliptic import Ellipic
from random import randint
from getpass import getpass
import logging


logger = logging.getLogger(__name__)


def generate_ecp(
                 message: bytes,
                 elliptic_params: dict,
                 d: int = 0, 
                 bits: int = 256,
                ) -> tuple[bytes, tuple[int, int]]:
    """
    Формирование электронной цифровой подписи (ЭЦП) по алгоритму
    ГОСТ Р 34.10-2012 для переданного сообщения.

    Функция реализует процесс подписания сообщения с использованием
    эллиптической кривой и хеш-функции ГОСТ Р 34.11-2012. На вход
    передаются байты сообщения, параметры эллиптической кривой,
    значение закрытого ключа подписи d (опционально) и размер
    хеш-функции.

    Процесс подписания выполняется по следующему алгоритму:

    1. Проверка корректности размера хеш-кода (`bits`):
       допускаются только значения 256 или 512 бит.

    2. Инициализация объекта эллиптической кривой `Ellipic`
       на основе параметров, переданных в `elliptic_params`.

    3. Получение закрытого ключа подписи d:
       - если d передан аргументом функции, используется он;
       - если d == 0, пользователю предлагается вручную ввести
         значение ключа из диапазона:

             0 < d < q

         где q — порядок подгруппы эллиптической кривой.

    4. Вычисление открытого ключа:

       Q = dP

       где:
           d — закрытый ключ,
           P — образующая точка подгруппы эллиптической кривой.

    5. Вычисление хеша сообщения при помощи алгоритма
       ГОСТ Р 34.11-2012 (Стрибог) длиной 256 или 512 бит.

    6. Преобразование хеша сообщения в целое число alpha
       и вычисление:

       e = alpha mod q

       Если:

       e = 0

       то устанавливается:

       e = 1

    7. Генерация случайного числа:

           0 < k < q

       и вычисление точки:

           C = kP

       После чего определяется:

           r = x mod q

       где:
           x — X-координата точки C.

       Если:

           r = 0

       выполняется повторная генерация k.

    8. Вычисление значения:

           s = (r * d + k * e) mod q

       Если:

           s = 0

       выполняется повторная генерация k.

    9. Формирование итоговой подписи ksi в бинарном виде
       посредством конкатенации:

           ksi = r || s

       где:
           r и s представлены как байтовые вектора фиксированной
           длины (32 байта для режима 256 бит и 64 байта
           для режима 512 бит).

    Args:
        message:
            Подписываемое сообщение в виде последовательности байт.

        elliptic_params:
            Словарь параметров эллиптической кривой.

            Ожидаемые ключи:

            - ``P`` (tuple[int, int]):
                образующая точка подгруппы.

            - ``q`` (int):
                порядок подгруппы.

            - ``a`` (int):
                коэффициент a эллиптической кривой.

            - ``b`` (int):
                коэффициент b эллиптической кривой.

            - ``p`` (int):
                характеристика конечного поля.

            Пример:

            {
                "P": (-2, 4),
                "q": 7,
                "a": 4,
                "b": 6,
                "p": 13
            }

        d:
            Закрытый ключ подписи.

            Должен удовлетворять условию:

                0 < d < q

            Если d == 0, значение будет запрошено
            у пользователя через консоль.

        bits:
            Размер хеш-кода алгоритма ГОСТ Р 34.11-2012.

            Допустимые значения:
                - 256
                - 512

            По умолчанию: 256.

    Returns:
        tuple[bytes, tuple[int, int]]:

            Кортеж из двух элементов:

            1. Электронная подпись ksi (`bytes`),
               сформированная как:

                   r || s

            2. Открытый ключ Q (`tuple[int, int]`):

                   Q = dP

    Raises:
        ValueError:
            Если передано недопустимое значение `bits`.

        ValueError:
            Если пользователь вводит некорректное значение
            закрытого ключа d (контролируется циклом ввода).

    Notes:
        Подпись формируется согласно процедуре,
        описанной в ГОСТ Р 34.10-2012.

        Для генерации случайного параметра k используется
        функция `randint()`, выбирающая значение из диапазона:

            [1, q - 1]

        Возвращаемая подпись хранится в бинарном формате и
        может быть записана в отдельный файл `.sig`.
    """
    # Шаг 0: Проверка переданных аргументов
    if bits not in (256, 512):
        raise ValueError("bits должен быть 256 или 512")
    
    E = Ellipic(**elliptic_params)
    
    if not d:
        while True:
            d = int(getpass(f"Укажите значение для ключа подписи (0 < d < {E.q}): "))
            if 0 < d < E.q:
                break

    logger.debug("Закрытый ключ подписи: %s", d)

    Q: tuple[int, int] = E.calculate_new_point(P=E.P, n=d)

    # Шаг 1: Генерация хеша исходного текста   
    gost = GOST341112(data=message, digest_size=bits)
    H = gost.hexdigest()

    logger.debug("Хеш-код исходного текста: %s", H)

    # Шаг 2: Вычислить alpha, e
    alpha = int.from_bytes(bytes.fromhex(H), 'big')

    e = alpha % E.q
    if e == 0:
        e = 1

    # Шаг 3: Сгенерировать целое число 0 < k < q
    while True:
        k: int = randint(1, E.q - 1) # т.к. метод выбирает число из промежутка [a, b]

        # Шаг 4: Вычислить C, r
        C: tuple[int, int] = E.calculate_new_point(P=E.P, n=k)
        X: int = C[0]
        r: int = X % E.q

        if r == 0:
            continue
    
        # Шаг 5: Вычислить число s
        s: int = (r * d + k * e) % E.q
        if s != 0:
            break
    
    logger.debug("Расчитано значение r: %s", r)
    logger.debug("Расчитано значение r: %s", s)

    # Шаг 6: Вычислить двоичные вектора r и s
    byte_length = bits // 8
    logger.debug("Размер двоичных векторов: %s", byte_length)

    r_bytes = r.to_bytes(byte_length, 'big')
    s_bytes = s.to_bytes(byte_length, 'big')

    # Получение ЭЦП: ksi = r || s
    ksi: bytes = r_bytes + s_bytes

    return ksi, Q


def verify_ecp(message: bytes, 
               ksi: bytes, 
               elliptic_params: dict,
               Q: tuple,
               bits: int = 256,) -> bool:
    """
    Проверка электронной цифровой подписи (ЭЦП) по алгоритму
    ГОСТ Р 34.10-2012 для переданного сообщения.

    Функция реализует процедуру верификации электронной подписи
    с использованием эллиптической кривой и хеш-функции
    ГОСТ Р 34.11-2012 (Стрибог).

    Проверка подписи выполняется по следующему алгоритму:

    1. Проверка корректности размера хеш-кода (`bits`):
    допускаются только значения 256 или 512 бит.

    2. Инициализация объекта эллиптической кривой `Ellipic`
    на основе параметров, переданных в `elliptic_params`.

    3. Извлечение значений `r` и `s` из подписи `ksi`.

    Подпись представляется как конкатенация:

        ksi = r || s

    где:
        - `r` — первая половина байтовой строки;
        - `s` — вторая половина байтовой строки.

    Значения преобразуются из байтового представления
    в целые числа.

    4. Проверка корректности значений подписи.

    Проверяется выполнение условий:

        0 < r < q
        0 < s < q

    где:
        q — порядок подгруппы эллиптической кривой.

    Если хотя бы одно условие не выполняется,
    подпись считается недействительной и функция
    немедленно возвращает `False`.

    5. Вычисление хеша исходного сообщения при помощи
    алгоритма ГОСТ Р 34.11-2012 (Стрибог)
    длиной 256 или 512 бит.

    6. Преобразование хеша сообщения в целое число
    `alpha` и вычисление:

        e = alpha mod q

    Если:

        e = 0

    устанавливается:

        e = 1

    7. Вычисление мультипликативной обратной величины:

    :contentReference[oaicite:0]{index=0}

    8. Вычисление промежуточных коэффициентов:

    :contentReference[oaicite:1]{index=1}

    :contentReference[oaicite:2]{index=2}

    9. Вычисление контрольной точки:

    :contentReference[oaicite:3]{index=3}

    где:
        - `P` — образующая точка подгруппы;
        - `Q` — открытый ключ подписи.

    10. Из X-координаты точки `C` вычисляется значение:

            R = x mod q

    11. Выполняется сравнение:

            R == r

    Если равенство выполняется — подпись считается
    корректной и возвращается `True`, иначе — `False`.

    Args:
        message:
            Проверяемое сообщение в виде последовательности
            байт.

        ksi:
            Электронная подпись в бинарном формате.

            Подпись должна представлять собой конкатенацию:

                r || s

            где:
                `r` и `s` представлены байтовыми векторами
                одинаковой длины.

        elliptic_params:
            Словарь параметров эллиптической кривой.

            Ожидаемые ключи:

            - ``P`` (tuple[int, int]):
                образующая точка подгруппы.

            - ``q`` (int):
                порядок подгруппы.

            - ``a`` (int):
                коэффициент `a` эллиптической кривой.

            - ``b`` (int):
                коэффициент `b` эллиптической кривой.

            - ``p`` (int):
                характеристика конечного поля.

            Пример:

            {
                "P": (-2, 4),
                "q": 7,
                "a": 4,
                "b": 6,
                "p": 13
            }

        Q:
            Открытый ключ подписи.

            Вычисляется на этапе подписания как:

    :contentReference[oaicite:4]{index=4}

            где:
                - `d` — закрытый ключ подписи;
                - `P` — образующая точка подгруппы.

        bits:
            Размер хеш-кода алгоритма ГОСТ Р 34.11-2012.

            Допустимые значения:
                - 256
                - 512

            По умолчанию: 256.

    Returns:
        bool:
            Результат проверки подписи.

            Возвращает:

            - `True` — если подпись корректна;
            - `False` — если подпись недействительна.

    Raises:
        ValueError:
            Если передано недопустимое значение `bits`.

    Notes:
        Проверка подписи реализуется согласно процедуре,
        описанной в ГОСТ Р 34.10-2012.

        Для вычисления обратного элемента используется
        метод `E.inv()`, реализующий вычисление
        мультипликативной обратной величины по модулю `q`.

        Подпись считается корректной только при выполнении
        условия:

            R == r

        где:
            `R` — вычисленное контрольное значение,
            `r` — значение, извлечённое из подписи.
    """
    
    # Шаг 0: Проверка
    if bits not in (256, 512):
        raise ValueError("bits должен быть 256 или 512")
    
    E = Ellipic(**elliptic_params)
    
    # Шаг 1: Получить значения r, s из ksi
    half = len(ksi) // 2

    r = int.from_bytes(ksi[:half], 'big')
    s = int.from_bytes(ksi[half:], 'big')

    if not (0 < r < E.q) or not (0 < s < E.q):
        return False

    # Шаг 2: Генерация хеша исходного текста   
    gost = GOST341112(data=message, digest_size=bits)
    H = gost.hexdigest()

    # Шаг 3: Вычислить alpha, e
    alpha = int.from_bytes(bytes.fromhex(H), 'big')

    e = alpha % E.q
    if e == 0:
        e = 1

    # Шаг 4: Вычислить v = e^(-1)(mod q)
    v: int = E.inv(x=e, p=E.q)

    # Шаг 5: Вычислить значения z1 = sv(mod q) и z2 = -rv(mod q)
    z1: int = (s * v) % E.q
    z2: int = (-r * v) % E.q

    # Шаг 6: Вычислить C=z1*P + z2* Q
    z1P = E.calculate_new_point(P=E.P, n=z1)
    z2Q = E.calculate_new_point(P=Q, n=z2)
    C = E._calculate_point(P=z1P, Q=z2Q)
    x: int = C[0]
    R: int = x % E.q

    return True if R == r else False


